#!/bin/bash
# Build mcomp-vault, the secrets vault behind `metacomputer secrets` (SECURITY.md,
# "Secrets and logins"). Needs Apple's Command Line Tools (swiftc); macOS 15+.
#
#   scripts/build-vault.sh              build, sign and install to
#                                       ~/.local/share/metacomputer/bin/mcomp-vault
#                                       (skipped when the installed one is this source)
#   scripts/build-vault.sh --force      rebuild and install even if it's up to date
#   scripts/build-vault.sh --out PATH   build a release binary at PATH; don't install
#   scripts/build-vault.sh --test PATH  build a TEST binary at PATH (never installed): it
#                                       honours MCOMP_VAULT_TEST_SSH (a stub instead of
#                                       /usr/bin/ssh), MCOMP_VAULT_TEST_LISTENERS and
#                                       MCOMP_VAULT_TEST_PROMPT_TIMEOUT; tests/test_secrets.py
#                                       uses it. Release builds don't contain that code.
#
# The guest-side fill script (vault/guest_fill.py) is compiled into the binary, so
# editing the repository's copy changes nothing until the vault is rebuilt.
# The binary is signed ad hoc with the hardened runtime: other processes of yours
# can't attach a debugger to it or inject libraries into it.
set -Eeuo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/vault"
INSTALL_DIR="$HOME/.local/share/metacomputer/bin"
INSTALLED="$INSTALL_DIR/mcomp-vault"
mode=install out="" force=0
while [ $# -gt 0 ]; do
  case "$1" in
    --force) force=1 ;;
    --out) mode=out; out="${2:?--out needs a path}"; shift ;;
    --test) mode=test; out="${2:?--test needs a path}"; shift ;;
    -h|--help) sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "build-vault: unknown option $1" >&2; exit 2 ;;
  esac
  shift
done
die() { echo "build-vault: $*" >&2; exit 1; }
command -v swiftc >/dev/null 2>&1 || die "swiftc not found: install Apple's Command Line Tools (xcode-select --install)"
[ "$(sw_vers -productVersion | cut -d. -f1)" -ge 15 ] || die "needs macOS 15 or later"

# The source this binary is built from (Swift files + the guest script).
src_hash="$(cat "$SRC"/*.swift "$SRC/guest_fill.py" | shasum -a 256 | cut -c1-16)"
if [ "$mode" = install ] && [ "$force" = 0 ] && [ -x "$INSTALLED" ] \
   && "$INSTALLED" version --json 2>/dev/null | grep -q "\"source\":\"$src_hash\"" \
   && "$INSTALLED" version --json 2>/dev/null | grep -q '"build":"release"'; then
  echo "mcomp-vault is up to date ($INSTALLED, source $src_hash)"
  exit 0
fi

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
gen="$tmp/GuestScript.swift"
grep -q '"""##' "$SRC/guest_fill.py" && die "vault/guest_fill.py contains the sequence that ends the embedded string"
{
  echo '// Generated by scripts/build-vault.sh: the guest-side fill script, built into the binary.'
  echo "let buildSourceHash = \"$src_hash\""
  echo 'let guestFillScript = ##"""'
  cat "$SRC/guest_fill.py"
  echo '"""##'
} > "$gen"

flags=(-O -swift-version 6 -target "$(uname -m)-apple-macos15.0")
[ "$mode" = test ] && flags+=(-D MCOMP_VAULT_TESTING)
swiftc "${flags[@]}" -o "$tmp/mcomp-vault" "$SRC"/*.swift "$gen"
codesign -s - -o runtime --force --identifier io.metavert.mcomp-vault "$tmp/mcomp-vault" 2>/dev/null \
  || die "codesign failed"
"$tmp/mcomp-vault" selftest >/dev/null || { "$tmp/mcomp-vault" selftest | grep FAIL >&2; die "the new binary failed its selftest"; }

case "$mode" in
  install)
    mkdir -p "$INSTALL_DIR"
    cp "$tmp/mcomp-vault" "$INSTALLED.new" && chmod 755 "$INSTALLED.new" && mv -f "$INSTALLED.new" "$INSTALLED"
    echo "installed $INSTALLED (source $src_hash, sha256 $(shasum -a 256 "$INSTALLED" | cut -c1-16)...)" ;;
  *)
    mkdir -p "$(dirname "$out")"
    cp "$tmp/mcomp-vault" "$out" && chmod 755 "$out"
    echo "built $out ($([ "$mode" = test ] && echo TEST || echo release) build, source $src_hash)" ;;
esac
