#!/usr/bin/env python3
"""Write what's made from the agents' manifests (coding-agents/<name>/manifest.json, in lib/agentkit/registry.py's order), so a
new agent is its folder, one registry line and a CHANGELOG line, and these follow from them:

    docs/agents.md          the index of agents: their install options, command, tools, what learn and bench do with
                            them, where their code and docs are
    lib/agentkit/agents.sh  the data metacomputer's bash needs (install.sh, bin/metacomputer): no agent is named in the
                            shared scripts themselves
    .github/CODEOWNERS      its agents' block: who reviews each agent's folder

    python3 scripts/gen-agents.py           write them
    python3 scripts/gen-agents.py --check   change nothing; exit 1 and list what isn't current (tests/test_agents.py)

A manifest is a contributor's input: nothing is made from the manifests until every one passes its checks (lib/agentkit/
manifests.py check, which names the agent and the field of each problem), and each value is then written for where it
lands (lib/gensafe.py: a shell word, Markdown text or code, a link, a CODEOWNERS line).

Works under any python3 (macOS's 3.9 included)."""
import os
import sys

LAB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(LAB, "lib"))
import gensafe  # noqa: E402
from agentkit import manifests, registry  # noqa: E402

BEGIN = "# >>> generated by scripts/gen-agents.py from the agents' manifests: don't edit by hand"
END = "# <<< generated by scripts/gen-agents.py"
CODEOWNERS = ".github/CODEOWNERS"
# What a manifest gives bash, by mc_agent FLAG KEY.
SHELL_KEYS = ("dir", "label", "prog", "docs", "missing", "steps", "only_note")


sh_quote = gensafe.sh_quote     # one shell word, in single quotes


def flags():
    return [manifests.manifest(n)["flag"] for n in registry.AGENTS]


def install_flags():
    """install.sh's options for the agents: --FLAG --no-FLAG --only-FLAG and each one's own, in the registry's order."""
    out = []
    for n in registry.AGENTS:
        m = manifests.manifest(n)
        out += [f"--{m['flag']}", f"--no-{m['flag']}", f"--only-{m['flag']}", *m["install"]["options"]]
    return out


def shell_value(name, key):
    m = manifests.manifest(name)
    return name if key == "dir" else m["install"][key] if key in ("missing", "steps", "only_note") else m[key]


def agents_sh():
    out = ["# metacomputer's coding agents, as bash reads them: made from coding-agents/<name>/manifest.json by",
           "# scripts/gen-agents.py (don't edit by hand: its --check fails a copy that isn't current). Sourced by install.sh",
           "# and bin/metacomputer; data and one lookup only, nothing runs.",
           f"MC_AGENTS={sh_quote(' '.join(registry.AGENTS))}",
           f"MC_AGENT_FLAGS={sh_quote(' '.join(flags()))}",
           f"MC_AGENT_GENERIC={sh_quote(' '.join(manifests.manifest(n)['flag'] for n in manifests.generic()))}",
           f"MC_AGENT_INSTALL_FLAGS={sh_quote(' '.join(install_flags()))}",
           f"MC_AGENT_LABELS_OR={sh_quote(manifests.in_words(manifests.labels()))}",
           f"MC_AGENT_RELEASE_FILE={sh_quote(manifests.release_file() or '')}",
           f"MC_AGENT_SWITCH_WORDS={sh_quote(manifests.switch_words())}",
           "mc_agent() { # FLAG KEY: that agent's dir (its folder under coding-agents/), label, prog, docs, missing (line or",
           "  # listed), steps (generic or hooks) or only_note; status 1: no such agent",
           "  case \"$1:$2\" in"]
    for n in registry.AGENTS:
        flag = manifests.manifest(n)["flag"]
        if not registry.PART.fullmatch(flag):        # a case pattern: checked again where it's written
            raise ValueError(f"coding-agents/{n}/manifest.json: its flag isn't a plain lowercase word")
        for key in SHELL_KEYS:
            out.append(f"    {flag}:{key}) printf '%s' {sh_quote(shell_value(n, key))} ;;")
    out += ["    *) return 1 ;;", "  esac", "}"]
    return "\n".join(out) + "\n"


def docs_index():
    rows = []
    for n in registry.AGENTS:
        m = manifests.manifest(n)
        code = (lambda v: gensafe.md_code(v, table=True))
        opts = ", ".join(code(o) for o in (f"--no-{m['flag']}", f"--only-{m['flag']}", *m["install"]["options"]))
        ses = m.get("sessions")
        rows.append((gensafe.md_text(m["label"]), code(m["prog"]), opts, code(m["tools"]),
                     ("yes (" + ("its transcript files" if ses["source"] == "files" else "its session databases") + ")")
                     if ses else "no",
                     code(f"--agent {m['bench']['switch']}") if m.get("bench") else "no",
                     gensafe.md_link(m["docs"], os.path.relpath(m["docs"], "docs")),
                     gensafe.md_link(f"coding-agents/{n}/", f"../coding-agents/{n}/")))
    head = ("Agent", "Command", "install.sh", "Tools", "`learn` reads it", "`bench`", "Docs", "Code")
    out = ["# Coding agents",
           "",
           "<!-- Made from coding-agents/<name>/manifest.json by scripts/gen-agents.py: don't edit by hand (its --check, run by "
           "tests/test_agents.py, fails a copy that isn't current). -->",
           "",
           "The coding agents metacomputer sets itself up for: every install (and `metacomputer update`) does each one "
           "installed on this Mac, unless you said `--no-...` (`./install.sh --help`). Each agent is a folder of its own, "
           "`coding-agents/<name>/` ([coding-agents/README.md](../coding-agents/README.md)), listed in `lib/agentkit/registry.py`; "
           "`metacomputer agents` shows how each is set up here.",
           "",
           "| " + " | ".join(head) + " |",
           "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    out += [""]
    return "\n".join(out)


def codeowners_block():
    out = [BEGIN.replace("the agents' manifests", "the agents' manifests (owners)")]
    for n in registry.AGENTS:
        out.append(gensafe.codeowners_line(f"/coding-agents/{n}/", manifests.manifest(n)["owners"]))
    out.append(END)
    return out


def splice(text, block, where):
    """TEXT with its generated block replaced by BLOCK (lines); ValueError when the markers aren't there once each."""
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.startswith(BEGIN[:37])]
    ends = [i for i, ln in enumerate(lines) if ln.startswith(END)]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{where}: its generated block's markers aren't there exactly once")
    return "\n".join(lines[:starts[0]] + block + lines[ends[0] + 1:])


def wanted():
    """{path: contents} of everything made here."""
    bad = [f"coding-agents/{n}/manifest.json: {b}" for n in registry.AGENTS for b in manifests.check(n)] + manifests.conflicts()
    if bad:
        raise ValueError("; ".join(bad))
    return {"docs/agents.md": docs_index(), "lib/agentkit/agents.sh": agents_sh(),
            CODEOWNERS: splice(read(CODEOWNERS), codeowners_block(), CODEOWNERS)}


def read(rel):
    with open(os.path.join(LAB, rel), encoding="utf-8") as f:
        return f.read()


def main(argv):
    import strictargs           # anything but [--check] (-hx, --bogus, a word) is refused before anything is written
    check = bool(strictargs.expect(argv, ["[--check]"], prog="gen-agents.py", usage=__doc__).opts.get("--check"))
    try:
        want = wanted()
    except (ValueError, OSError) as e:
        print(f"gen-agents.py: {e}", file=sys.stderr)
        return 1
    stale = [rel for rel, text in want.items() if not os.path.isfile(os.path.join(LAB, rel)) or read(rel) != text]
    if check:
        for rel in stale:
            print(f"not current: {rel} (python3 scripts/gen-agents.py writes it)")
        return 1 if stale else 0
    for rel in stale:
        p = os.path.join(LAB, rel)
        mode = os.stat(p).st_mode & 0o777 if os.path.exists(p) else 0o644
        tmp = p + ".gen-agents.tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(want[rel])
        os.chmod(tmp, mode)
        os.replace(tmp, p)
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
