#!/usr/bin/env python3
"""Write what's made from the sinks' manifests (sinks/<kind>/manifest.json, in lib/sinkkit/registry.py's order), so a
new kind of sink is its folder, one registry line and a CHANGELOG line, and these follow from them:

    docs/sinks.md           the index of kinds: what each sends, its settings, whether the vault's audit sinks have it,
                            where its code and docs are
    bin/metacomputer        its usage line for `metacomputer events` (the kinds, as `metacomputer help` lists them)
    .github/CODEOWNERS      its sinks' block: who reviews each kind's folder

The vault's part (what its audit sinks share with the stream) isn't kept in the repository: scripts/build-vault.sh makes
it at build time (lib/sinkkit/vault.py).

    python3 scripts/gen-sinks.py           write them
    python3 scripts/gen-sinks.py --check   change nothing; exit 1 and list what isn't current (tests/test_events.py)

A manifest is a contributor's input: nothing is made from the manifests until every one passes its checks (lib/sinkkit/
vault.py check, which names the kind and the field of each problem), and each value is then written for where it lands
(lib/gensafe.py: a shell comment's text, Markdown text or code, a link, a CODEOWNERS line).

Works under any python3 (macOS's 3.9 included)."""
import os
import re
import sys

LAB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(LAB, "lib"))
import gensafe  # noqa: E402
from sinkkit import manifests, registry, vault  # noqa: E402

BEGIN = "# >>> generated by scripts/gen-sinks.py from the sinks' manifests (owners): don't edit by hand"
END = "# <<< generated by scripts/gen-sinks.py"
CODEOWNERS = ".github/CODEOWNERS"
# bin/metacomputer's line for the event stream in its usage (its header, which `metacomputer help` prints as it is):
# the part between these is the kinds' help words.
USAGE = re.compile(r"^(#\s+the optional event stream: )(.*)( \(docs/events\.md\))$", re.M)


def yes(v):
    return "yes" if v else "no"


def docs_index():
    rows = []
    for k in registry.SINKS:
        m = manifests.manifest(k)
        page, _, anchor = m["docs"].partition("#")
        v = m.get("vault")
        rows.append((gensafe.md_code(k, table=True), gensafe.md_text(m["about"]), gensafe.md_text(m["batch"]),
                     yes(m["headers"]), yes(m["signed"]), yes(m["phone"]),
                     ("yes" + ("" if v["acknowledges"] else " (never --required)")) if v else "no",
                     gensafe.md_link(page, f"{os.path.relpath(page, 'docs')}{'#' + anchor if anchor else ''}"),
                     gensafe.md_link(f"sinks/{k}/", f"../sinks/{k}/")))
    head = ("Kind", "What it sends", "Events a request", "Headers", "Signed", "A phone", "The vault's audit sinks", "Docs",
            "Code")
    out = ["# Event sinks",
           "",
           "<!-- Made from sinks/<kind>/manifest.json by scripts/gen-sinks.py: don't edit by hand (its --check, run by "
           "tests/test_events.py, fails a copy that isn't current). -->",
           "",
           "The kinds of sink `metacomputer events sink add NAME --kind KIND --url URL` takes "
           "([docs/events.md](events.md): what the event stream sends, when and how, and each kind's format). Each kind "
           "is a folder of its own, `sinks/<kind>/` ([sinks/README.md](../sinks/README.md)), listed in "
           "`lib/sinkkit/registry.py`. The secrets vault's audit sinks (`metacomputer secrets audit-sink add`) have the "
           "kinds marked so in their column, in the same wrappings around the vault's own records, which they sign "
           "([SECURITY.md](../SECURITY.md)); one that must acknowledge every record (`--required`) can't be of a kind "
           "whose receivers don't.",
           "",
           "- **Events a request**: at most this many in one request (or one connection).",
           "- **Signed**: the event stream gives each sink of the kind a key of its own, and every request carries "
           "`sha256=HMAC(body)` under it.",
           "- **A phone**: a sink for a person's phone has its own cap (10 in any 10 minutes, 30 in any hour), and "
           "announcements of sink changes waiting for it go as one message.",
           "",
           "| " + " | ".join(head) + " |",
           "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    out += [""]
    return "\n".join(out)


def usage_line(text):
    """bin/metacomputer with its usage line for the event stream current; ValueError when it isn't there once."""
    found = USAGE.findall(text)
    if len(found) != 1:
        raise ValueError("bin/metacomputer: its usage line for the event stream (\"the optional event stream: ... "
                         "(docs/events.md)\") isn't there exactly once")
    words = ", ".join(gensafe.sh_comment(manifests.manifest(k)["help"]) for k in registry.SINKS)   # a comment's line
    return USAGE.sub(lambda m: m.group(1) + words + m.group(3), text, count=1)


def codeowners_block():
    out = [BEGIN]
    for k in registry.SINKS:
        out.append(gensafe.codeowners_line(f"/sinks/{k}/", manifests.manifest(k)["owners"]))
    out.append(END)
    return out


def splice(text, block, where):
    """TEXT with its generated block replaced by BLOCK (lines); ValueError when the markers aren't there once each."""
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.startswith(BEGIN[:36])]
    ends = [i for i, ln in enumerate(lines) if ln.startswith(END)]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{where}: its generated block's markers aren't there exactly once")
    return "\n".join(lines[:starts[0]] + block + lines[ends[0] + 1:])


def wanted():
    """{path: contents} of everything made here."""
    bad = vault.check() + manifests.conflicts()
    if bad:
        raise ValueError("; ".join(bad))
    return {"docs/sinks.md": docs_index(), "bin/metacomputer": usage_line(read("bin/metacomputer")),
            CODEOWNERS: splice(read(CODEOWNERS), codeowners_block(), CODEOWNERS)}


def read(rel):
    with open(os.path.join(LAB, rel), encoding="utf-8") as f:
        return f.read()


def main(argv):
    import strictargs           # anything but [--check] (-hx, --bogus, a word) is refused before anything is written
    check = bool(strictargs.expect(argv, ["[--check]"], prog="gen-sinks.py", usage=__doc__).opts.get("--check"))
    try:
        want = wanted()
    except (ValueError, OSError) as e:
        print(f"gen-sinks.py: {e}", file=sys.stderr)
        return 1
    stale = [rel for rel, text in want.items() if not os.path.isfile(os.path.join(LAB, rel)) or read(rel) != text]
    if check:
        for rel in stale:
            print(f"not current: {rel} (python3 scripts/gen-sinks.py writes it)")
        return 1 if stale else 0
    for rel in stale:
        p = os.path.join(LAB, rel)
        mode = os.stat(p).st_mode & 0o777 if os.path.exists(p) else 0o644
        tmp = p + ".gen-sinks.tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(want[rel])
        os.chmod(tmp, mode)
        os.replace(tmp, p)
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
