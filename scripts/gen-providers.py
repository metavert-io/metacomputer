#!/usr/bin/env python3
"""Write what's made from the providers' manifests (providers/<name>/manifest.py, in lib/cloud/registry.py's order),
so a new provider is its folder, one registry line and a CHANGELOG line, and these follow from them:

    docs/providers.md      the index of providers: what each has, what it bills, where its code and docs are
    lib/cloud/providers.sh the data metacomputer's bash needs (labels, credentials, options, words): no provider is
                           named in the shared scripts themselves
    the credential lines   in bin/metacomputer, scripts/lib.sh and scripts/remote-build.sh, between their
                           "generated by scripts/gen-providers.py" markers: they take every provider's credentials off
                           the environment before any other program runs, before bin/metacomputer even knows where its
                           checkout is (bash builtins only), so they can't read a file first
    .github/CODEOWNERS     its providers' block: who reviews each provider's folder

    python3 scripts/gen-providers.py           write them
    python3 scripts/gen-providers.py --check   change nothing; exit 1 and list what isn't current (tests/test_cloud_adapters.py)

A manifest is a contributor's input: nothing is made from the manifests until every provider's passes its checks
(problems(): lib/cloud/capabilities.py check_manifest and lib/cloud/manifests.py check_cli, which name the provider and
the field of each problem), and each value is then written for where it lands (lib/gensafe.py: a shell word, Markdown
text or code, a link, a CODEOWNERS line).

Works under any python3 (macOS's 3.9 included)."""
import os
import sys

LAB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(LAB, "lib"))
import cloud  # noqa: E402
import gensafe  # noqa: E402
from cloud import manifests  # noqa: E402

BEGIN = "# >>> generated by scripts/gen-providers.py from the providers' manifests: don't edit by hand"
END = "# <<< generated by scripts/gen-providers.py"
BLOCK_FILES = ("bin/metacomputer", "scripts/lib.sh", "scripts/remote-build.sh")
CODEOWNERS = ".github/CODEOWNERS"


sh_quote = gensafe.sh_quote     # one shell word, in single quotes


def problems():
    """What's wrong with the providers' manifests, each naming the provider and the field: [str] (empty: nothing)."""
    from cloud import capabilities
    bad = []
    for name in cloud.registry.PROVIDERS:
        cli = manifests.check_cli(name)
        bad += [f"providers/{name}/manifest.py: {b}" for b in cli]
        if not cli:
            bad += [f"providers/{name}/manifest.py: MANIFEST {b}"
                    for b in capabilities.check_manifest(manifests.manifest(name))]
    return bad + manifests.option_conflicts()


def credential_block():
    bad = [n for n in manifests.credentials() if gensafe.matches(n, r"[A-Z][A-Z0-9_]{1,63}", "x")]
    if bad:                         # unquoted words of a for loop: checked again where they're written
        raise ValueError(f"credentials that aren't environment variables' names: {bad!r}")
    names = " ".join(manifests.credentials())
    return [BEGIN,
            f"for mc_k in {names}; do export -n \"$mc_k\"; done; unset mc_k",
            END]


def cloud_usage():
    """`cloud`'s usage words for the providers' own options: " [--org ORG]" for --org."""
    out = ""
    for opt, _env in manifests.cloud_options():
        out += f" [{opt} {opt[2:].upper().replace('-', '_')}]"
    return out


def providers_sh():
    out = ["# metacomputer's providers, as bash reads them: made from providers/<name>/manifest.py by",
           "# scripts/gen-providers.py (don't edit by hand: its --check fails a copy that isn't current). Sourced by",
           "# scripts/lib.sh; data and one lookup only, nothing runs.",
           f"MC_PROVIDERS={sh_quote(' '.join(cloud.registry.PROVIDERS))}",
           f"MC_PROVIDER_ENV={sh_quote(' '.join(manifests.credentials()))}",
           f"MC_PROVIDER_COPY_KEYS={sh_quote(' '.join(manifests.copy_settings()))}",
           f"MC_PROVIDER_CREATE_OPTIONS={sh_quote(' '.join(o[0] for o in manifests.create_options()))}",
           f"MC_PROVIDER_CREATE_ONLY={sh_quote(' '.join(o[0] for o in manifests.create_options() if o[3]))}",
           f"MC_PROVIDER_CLOUD_OPTIONS={sh_quote(' '.join(o for o, _e in manifests.cloud_options()))}",
           # `cloud`'s usage and its value options, as metacomputer's command-line rules take them (bin/metacomputer)
           f"MC_PROVIDER_CLOUD_USAGE={sh_quote(cloud_usage())}",
           f"MC_PROVIDER_CLOUD_VALUES={sh_quote(''.join(o + '= ' for o, _e in manifests.cloud_options()))}",
           f"MC_TRANSPORT_SETTINGS={sh_quote(' '.join(manifests.transport_settings()))}",
           "mc_pv() { # PROVIDER KEY: that provider's word for KEY (lib/cloud/manifests.py shell_words); status 1: none",
           "  case \"$1:$2\" in"]
    for name in cloud.registry.PROVIDERS:
        if not cloud.registry.PART.fullmatch(name):     # a case pattern: checked again where it's written
            raise ValueError(f"lib/cloud/registry.py: {name!r} isn't a provider's name")
        for key, value in manifests.shell_words(name):
            out.append(f"    {name}:{key}) printf '%s' {sh_quote(value)} ;;")
    out += ["    *) return 1 ;;", "  esac", "}",
            "mc_pv_option() { # OPTION KEY: a provider's own vm create option's needs, default (its variable) or provider",
            "  case \"$1:$2\" in"]
    for opt, needs, default, _only, name in manifests.create_options():
        if gensafe.matches(opt, r"--[a-z][a-z0-9-]{1,30}", "an option"):     # a case pattern too
            raise ValueError(f"providers/{name}/manifest.py: create_options {opt!r} isn't an option")
        out.append(f"    {opt}:needs) printf '%s' {sh_quote(needs)} ;;")
        if default:
            out.append(f"    {opt}:default) printf '%s' {sh_quote(default)} ;;")
        out.append(f"    {opt}:provider) printf '%s' {sh_quote(name)} ;;")
    out += ["    *) return 1 ;;", "  esac", "}"]
    return "\n".join(out) + "\n"


def docs_index():
    from cloud import capabilities
    rows = []
    for name in cloud.registry.PROVIDERS:
        m, cli = manifests.manifest(name), manifests.cli(name)
        oe = m["outside_egress"]
        outside = ("none (only its own firewall)" if not oe["enforced"] else ", ".join(
            w for k, w in (("private_ranges", "private ranges refused"), ("metadata", "metadata refused"),
                           ("off", "can be turned off")) if oe[k]) or "enforced")
        code = (lambda v: gensafe.md_code(v, table=True))
        rows.append((gensafe.md_text(m["label"]), code(m["place"]), code(m["sleep_wake"]["kind"]),
                     ", ".join(capabilities.persist_modes(m)) or "none",
                     "yes" if m["snapshots"] else "no", code(m["egress"]["model"]), outside,
                     code(m["billing"]["stopped"]), "yes" if m["input"]["background"] else "no (foreground)",
                     ", ".join(code(c) for c in cli["credentials"]) or gensafe.md_text(cli["credential_words"]),
                     gensafe.md_link(cli["docs"], os.path.relpath(cli["docs"], "docs")),
                     gensafe.md_link(f"providers/{name}/", f"../providers/{name}/")))
    head = ("Provider", "`--on`", "Sleep", "PERSIST", "Snapshots", "Egress", "Outside the computer",
            "Stopped bills", "Background input", "Credentials", "Docs", "Code")
    out = ["# Providers",
           "",
           "<!-- Made from providers/<name>/manifest.py by scripts/gen-providers.py: don't edit by hand (its --check, "
           "run by tests/test_cloud_adapters.py, fails a copy that isn't current). -->",
           "",
           "Where metacomputer can make a computer besides this Mac and your own server (docs/remote.md). Each provider "
           "is a folder of its own, `providers/<name>/` ([providers/README.md](../providers/README.md)), listed in "
           "`lib/cloud/registry.py`. What each one has is its manifest's (`lib/cloud/capabilities.py` says what the "
           "fields mean); its docs page says how to set it up and what keeps it apart.",
           "",
           "| " + " | ".join(head) + " |",
           "|" + "---|" * len(head)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    out += ["", "What each bills while stopped (`Stopped bills`): `storage` its disk only, `full` everything, as if it "
                "ran. `Sleep`: `stop-start` (metacomputer stops and starts it through the provider), `auto-sleep` (it "
                "sleeps by itself when nothing is connected).", ""]
    for name in cloud.registry.PROVIDERS:
        m = manifests.manifest(name)
        out += [f"## {gensafe.md_text(m['label'])}", "", f"- Billing: {gensafe.md_text(m['billing']['note'])}.",
                f"- Input: {gensafe.md_text(m['input']['note'])}." if not m["input"]["background"] else
                "- Input: background input (the driver's virtual devices) works there.",
                f"- Sizes: {', '.join(gensafe.md_code(s) for s in m['sizes'])}." if m["sizes"] else
                "- Sizes: the provider chooses.",
                f"- Regions: {', '.join(gensafe.md_code(r) for r in m['regions'])}." if m["regions"] else
                "- Regions: not chosen per computer.", ""]
    return "\n".join(out)


def codeowners_block():
    out = [BEGIN.replace("the providers' manifests", "the providers' manifests (CLI owners)")]
    for name in cloud.registry.PROVIDERS:
        out.append(gensafe.codeowners_line(f"/providers/{name}/", manifests.cli(name)["owners"]))
    out.append(END)
    return out


def splice(text, block, where):
    """TEXT with its generated block replaced by BLOCK (lines); ValueError when the markers aren't there once each."""
    lines = text.split("\n")
    starts = [i for i, ln in enumerate(lines) if ln.startswith(BEGIN[:40])]
    ends = [i for i, ln in enumerate(lines) if ln.startswith(END)]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise ValueError(f"{where}: its generated block's markers aren't there exactly once")
    return "\n".join(lines[:starts[0]] + block + lines[ends[0] + 1:])


def wanted():
    """{path: contents} of everything made here; ValueError, naming each problem, when a manifest isn't sound."""
    bad = problems()
    if bad:
        raise ValueError("; ".join(bad))
    out = {"docs/providers.md": docs_index(), "lib/cloud/providers.sh": providers_sh()}
    for rel in BLOCK_FILES:
        out[rel] = splice(read(rel), credential_block(), rel)
    out[CODEOWNERS] = splice(read(CODEOWNERS), codeowners_block(), CODEOWNERS)
    return out


def read(rel):
    with open(os.path.join(LAB, rel), encoding="utf-8") as f:
        return f.read()


def main(argv):
    import strictargs           # anything but [--check] (-hx, --bogus, a word) is refused before anything is written
    check = bool(strictargs.expect(argv, ["[--check]"], prog="gen-providers.py", usage=__doc__).opts.get("--check"))
    try:
        want = wanted()
    except (ValueError, OSError) as e:
        print(f"gen-providers.py: {e}", file=sys.stderr)
        return 1
    stale = [rel for rel, text in want.items() if not os.path.isfile(os.path.join(LAB, rel)) or read(rel) != text]
    if check:
        for rel in stale:
            print(f"not current: {rel} (python3 scripts/gen-providers.py writes it)")
        return 1 if stale else 0
    for rel in stale:
        p = os.path.join(LAB, rel)
        mode = os.stat(p).st_mode & 0o777 if os.path.exists(p) else 0o644
        tmp = p + ".gen-providers.tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(want[rel])
        os.chmod(tmp, mode)
        os.replace(tmp, p)
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
